/**
 * Ready-to-play creatures transcribed from the Monster Manual, plus objects
 * built from the Dungeon Master's Guide tables.
 *
 * A stat block creature is described entirely by its type, size, and printed
 * numbers. It has no race, class, background, or level, because creature types
 * "have no rules of their own" (Monster Manual, "Statistics"). Armor class and
 * hit points are the values on the page rather than anything derived from the
 * gear it happens to be carrying.
 */

/** Ability scores in stat block order: STR, DEX, CON, INT, WIS, CHA. */
type AbilityLine = [number, number, number, number, number, number];

interface MonsterEntry {
  id: string;
  kind: TokenKind;
  name: string;
  creatureType: CreatureType;
  size: CreatureSize;
  /** Parenthetical tags after the type, such as "goblinoid" or "shapechanger". */
  tags?: string[];
  alignment: string;
  challenge: ChallengeRating;
  ac: number;
  armorNote?: string;
  hitDice: number;
  speeds?: Partial<CreatureSpeeds>;
  abilities: AbilityLine;
  saves?: Array<keyof AbilityScores>;
  /** Printed skill totals, not bonuses stacked on an ability modifier. */
  skills?: Record<string, number>;
  senses?: string[];
  languages?: string[];
  vulnerabilities?: string[];
  resistances?: string[];
  damageImmunities?: string[];
  conditionImmunities?: string[];
  /** Special traits, printed above the actions. */
  traits?: Array<[string, string]>;
  /** Actions, bonus actions, and reactions. */
  actions?: Array<[string, string]>;
  notes: string;
  wallet?: Wallet;
  /** Overrides the footprint implied by the creature's size. */
  width?: number;
  height?: number;
  sourcePage: number;
}

