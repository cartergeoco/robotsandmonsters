function toTraits(entries: Array<[string, string]> | undefined, prefix: string): Trait[] {
  return (entries ?? []).map(([name, description], index) => ({
    id: `${prefix}-${index}`,
    name,
    description,
  }));
}

function blueprintFor(entry: MonsterEntry): TokenBlueprint {
  const abilities: AbilityScores = {
    str: entry.abilities[0],
    dex: entry.abilities[1],
    con: entry.abilities[2],
    int: entry.abilities[3],
    wis: entry.abilities[4],
    cha: entry.abilities[5],
  };
  const statBlock = createStatBlock({
    tags: entry.tags ?? [],
    alignment: entry.alignment,
    challenge: entry.challenge,
    armorNote: entry.armorNote ?? "",
    hitDice: entry.hitDice,
    speeds: entry.speeds,
    saveProficiencies: entry.saves ?? [],
    senses: entry.senses ?? [],
    languages: entry.languages ?? [],
    vulnerabilities: entry.vulnerabilities ?? [],
    resistances: entry.resistances ?? [],
    damageImmunities: entry.damageImmunities ?? [],
    conditionImmunities: entry.conditionImmunities ?? [],
    sourcePage: entry.sourcePage,
  });
  const maxHp = statBlockHitPoints(statBlock, entry.size, abilities.con);
  const footprint = SIZE_PROFILES[entry.size].cells;
  const width = entry.width ?? footprint;
  const height = entry.height ?? footprint;

  return {
    id: entry.id,
    source: "built-in",
    kind: entry.kind,
    name: entry.name,
    color: TYPE_COLORS[entry.creatureType],
    stance: defaultStanceForKind(entry.kind),
    visualScale: 1,
    notes: entry.notes,
    // A stat block creature has no ancestry: its type and numbers are the whole build.
    raceId: "",
    subraceId: "",
    classId: "",
    subclassId: "",
    backgroundId: "",
    race: "",
    subrace: "",
    className: "",
    subclass: "",
    backgroundName: "",
    ruleChoices: {},
    abilityImprovements: [],
    creatureType: entry.creatureType,
    size: entry.size,
    level: 1,
    hp: maxHp,
    maxHp,
    ac: entry.ac,
    abilities,
    skills: Object.entries(entry.skills ?? {}).map(([name, bonus]) => ({
      id: `${entry.id}-skill-${name.toLowerCase().replace(/\s+/g, "-")}`,
      name,
      bonus,
    })),
    traits: toTraits(entry.traits, `${entry.id}-trait`),
    features: toTraits(entry.actions, `${entry.id}-action`),
    inventory: [],
    wallet: entry.wallet ?? { copper: 0, silver: 0, gold: 0 },
    statuses: [],
    statBlock,
    width,
    height,
    bounds: rectangularTokenBounds(width, height),
  };
}

export const HANDBOOK_MONSTERS: TokenBlueprint[] = MONSTERS.map(blueprintFor);
